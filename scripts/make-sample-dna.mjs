/**
 * Generates a synthetic 23andMe-format raw data file for the demo.
 *
 * Real exports are 600,000+ rows and ~25 MB, which is more than belongs in a
 * git repository. This produces a structurally identical file at a committable
 * size — same header, same column layout, same marker rsIDs at their real
 * genomic coordinates — carrying the demo patient's genotypes.
 *
 * Entirely fabricated. No real person's genome is represented.
 *
 * Run: node scripts/make-sample-dna.mjs
 */

import { writeFile, mkdir } from "node:fs/promises";
import { join } from "node:path";

const OUT = join(process.cwd(), "public", "sample-23andme.txt");
const FILLER_ROWS = 120_000;

/**
 * The demo patient, at real coordinates (GRCh37) so the file survives
 * inspection by anyone who knows what they're looking at.
 */
const MARKERS = [
  // CYP2C19 *2/*2 — poor metaboliser. Drives the clopidogrel finding.
  { rsid: "rs4244285", chr: "10", pos: 96541616, genotype: "AA" },
  { rsid: "rs4986893", chr: "10", pos: 96540410, genotype: "GG" },
  { rsid: "rs12248560", chr: "10", pos: 96521657, genotype: "CC" },
  // CYP2D6 *4/*4 — poor metaboliser. Drives the codeine finding.
  { rsid: "rs3892097", chr: "22", pos: 42524947, genotype: "TT" },
  // SLCO1B1 *5/*5 — poor function. Drives the simvastatin finding.
  { rsid: "rs4149056", chr: "12", pos: 21331549, genotype: "CC" },
  // CYP2C9 *1/*3 — intermediate.
  { rsid: "rs1799853", chr: "10", pos: 96702047, genotype: "CC" },
  { rsid: "rs1057910", chr: "10", pos: 96741053, genotype: "AC" },
  // Normal-function results, so the report is not uniformly alarming.
  { rsid: "rs116855232", chr: "13", pos: 48611918, genotype: "GG" },
  { rsid: "rs3918290", chr: "1", pos: 97915614, genotype: "CC" },
];

/** Deterministic PRNG, so regenerating the file produces identical output. */
function mulberry32(seed) {
  return () => {
    seed |= 0;
    seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

async function main() {
  const rand = mulberry32(20260725);
  const genotypes = ["AA", "AG", "GG", "CC", "CT", "TT", "AC", "GT", "--"];

  const lines = [
    "# This data file generated by 23andMe at: Sat Jul 25 09:14:02 2026",
    "# This file contains raw genotype data, including data that is not used in 23andMe reports.",
    "# This data has undergone a general quality review however only a subset of markers have been",
    "# individually validated for accuracy. As such, this data is suitable only for research,",
    "# educational, and informational use and not for medical or other use.",
    "#",
    "# SYNTHETIC SAMPLE — fabricated for demonstration. Not a real person's genome.",
    "#",
    "# Below is a text version of your data.  Fields are TAB-separated",
    "# Each line corresponds to a single SNP.  For each SNP, we provide its identifier",
    "# (an rsid or an internal id), its location on the reference human genome, and the",
    "# genotype call oriented with respect to the plus strand on the human reference sequence.",
    "#",
    "# rsid\tchromosome\tposition\tgenotype",
  ];

  // Interleave the real markers through the filler so they are not clustered
  // at the top — the parser has to actually scan the file to find them.
  const markerAt = new Map();
  for (let i = 0; i < MARKERS.length; i++) {
    markerAt.set(Math.floor(((i + 1) * FILLER_ROWS) / (MARKERS.length + 1)), MARKERS[i]);
  }

  // Sequential filler IDs collide with real marker rsIDs — rs1000000 + 57910
  // is rs1057910, the CYP2C9*3 marker — and a duplicate row would corrupt the
  // call it collides with. Skip any ID that belongs to a real marker.
  const reserved = new Set(MARKERS.map((m) => m.rsid));

  for (let i = 0; i < FILLER_ROWS; i++) {
    const marker = markerAt.get(i);
    if (marker) {
      lines.push(`${marker.rsid}\t${marker.chr}\t${marker.pos}\t${marker.genotype}`);
      continue;
    }
    const rsid = `rs${1_000_000 + i}`;
    if (reserved.has(rsid)) continue;

    const chr = 1 + Math.floor(rand() * 22);
    const pos = 10_000 + Math.floor(rand() * 240_000_000);
    const gt = genotypes[Math.floor(rand() * genotypes.length)];
    lines.push(`${rsid}\t${chr}\t${pos}\t${gt}`);
  }

  const text = lines.join("\n");
  await mkdir(join(process.cwd(), "public"), { recursive: true });
  await writeFile(OUT, text, "utf8");

  console.log(`Wrote ${OUT}`);
  console.log(`  ${lines.length.toLocaleString()} lines, ${(text.length / 1024 / 1024).toFixed(1)} MB`);
  console.log(`  ${MARKERS.length} pharmacogenomic markers embedded`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
